await page.getByRole('button',{name:'Details for Test Show, S01 · E01'}).waitFor();
await page.getByRole('button',{name:'Add Test Show to watchlist'}).first().click();
await page.getByRole('button',{name:/Watchlist1/}).click();
assert.equal(await page.locator('.media-card').count(),1);
await page.getByRole('button',{name:'Home',exact:true}).click();
await page.getByRole('button',{name:'Details for Test Show, S01 · E01'}).click();
await page.locator('.details').getByRole('button',{name:'▶ Play',exact:true}).click();
await page.waitForFunction(()=>{const v=document.querySelector('video');return v&&v.duration>0&&v.currentTime>0.1;});
await page.evaluate(()=>{const v=document.querySelector('video');v.currentTime=3;v.pause();});
